public class tapsiriq8_saygac {
    public static void main(String[] args) {

        // Tapşırıq:
        // do-while dövrəsindən istifadə edərək
        // 1-dən 10-a qədər olan ədədləri
        // hər birini yeni sətirdə ekrana çap etmək.

        int i = 1;

        do {
            System.out.println(i);
            i++;
        } while (i <= 10);

    }
}
